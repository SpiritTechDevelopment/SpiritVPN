-- Общие для всех транзакций служебные запросы.

-- Возвращает время начала транзакции. Выполняется первым оператором: now() внутри
-- транзакции неизменен, поэтому одно это значение задаёт «сейчас» для всех
-- доменных решений команды — истечения entitlement, отметок исчерпания квоты и
-- границы периодов (решение 2, §11.1).
--
-- Время процесса (app.Clock) для этого непригодно: расхождение часов приложения и
-- базы означало бы, что closed_at старого периода и started_at нового разъедутся и
-- дельта трафика не попадёт ни в один период (§11, §12).
-- name: SelectTransactionNow :one
SELECT now()::timestamptz AS now;
